"""
نرمال‌سازی و پاک‌سازی ارقام.

این ماژول دو دسته تابع ارائه می‌دهد:

    ۱. تبدیل ارقام فارسی/عربی به ASCII (normalize_digits).
    ۲. حذف کاراکترهای غیرعددی یا غیرحرف‌وعددی از یک رشته
       (strip_non_digits و strip_non_alphanumeric).

توابع دستهٔ دوم به‌صورت خودکار ارقام فارسی و عربی را نیز به ASCII
تبدیل می‌کنند؛ بنابراین ورودی‌های فارسی/عربی را هم به‌درستی پردازش
می‌کنند.

در متن‌های فارسی، ارقام می‌توانند به سه شکل مختلف ظاهر شوند:

    - ارقام فارسی:  ۰۱۲۳۴۵۶۷۸۹  (U+06F0 تا U+06F9)
    - ارقام عربی:   ٠١٢٣٤٥٦٧٨٩  (U+0660 تا U+0669)
    - ارقام ASCII:  0123456789  (U+0030 تا U+0039)
"""

from __future__ import annotations

import re

__all__ = [
    "normalize_digits",
    "strip_non_digits",
    "strip_non_alphanumeric",
]


# ---------------------------------------------------------------------------
# تبدیل ارقام فارسی و عربی به ASCII
# ---------------------------------------------------------------------------

# ارقام فارسی، عربی و ASCII
_PERSIAN_DIGITS = "۰۱۲۳۴۵۶۷۸۹"
_ARABIC_DIGITS = "٠١٢٣٤٥٦٧٨٩"
_ASCII_DIGITS = "0123456789"

# جدول تبدیل: هم ارقام فارسی و هم ارقام عربی به ASCII تبدیل می‌شوند.
_DIGIT_TRANSLATION = str.maketrans(
    _PERSIAN_DIGITS + _ARABIC_DIGITS,
    _ASCII_DIGITS + _ASCII_DIGITS,
)


def normalize_digits(text: str) -> str:
    """تبدیل ارقام فارسی و عربی به ارقام ASCII.

    Args:
        text: متن ورودی که ممکن است شامل ارقام فارسی یا عربی باشد.

    Returns:
        متن با ارقام ASCII (0-9).

    مثال:
        >>> normalize_digits("۱۲۳۴")
        '1234'
        >>> normalize_digits("١٢٣٤")
        '1234'
        >>> normalize_digits("می‌خواهم ۵ عدد بخرم")
        'می‌خواهم 5 عدد بخرم'
    """
    return text.translate(_DIGIT_TRANSLATION)


# ---------------------------------------------------------------------------
# حذف کاراکترهای غیرعددی و غیرحرف‌وعددی
# ---------------------------------------------------------------------------

_NON_DIGIT_RE = re.compile(r"\D")
_NON_ALPHANUMERIC_RE = re.compile(r"[^A-Za-z0-9]")


def strip_non_digits(text: str) -> str:
    """حذف همهٔ کاراکترهای غیرعددی از یک رشته.

    ابتدا ارقام فارسی و عربی را به ASCII تبدیل می‌کند، سپس همهٔ
    کاراکترهای غیرعددی را حذف می‌کند. بنابراین ورودی با ارقام
    فارسی/عربی هم به‌درستی پردازش می‌شود.

    Args:
        text: رشتهٔ ورودی خام.

    Returns:
        رشته‌ای که فقط شامل ارقام ASCII (0-9) است.

    مثال:
        >>> strip_non_digits("4111-1111-1111-1111")
        '4111111111111111'
        >>> strip_non_digits("۴۱۱۱-۱۱۱۱-۱۱۱۱-۱۱۱۱")
        '4111111111111111'
        >>> strip_non_digits("قیمت: ۱۲,۳۴۵ تومان")
        '12345'
        >>> strip_non_digits("abc")
        ''
    """
    # گام ۱: تبدیل ارقام فارسی/عربی به ASCII
    text = normalize_digits(text)
    # گام ۲: حذف کاراکترهای غیرعددی
    return _NON_DIGIT_RE.sub("", text)


def strip_non_alphanumeric(text: str) -> str:
    """حذف همهٔ کاراکترهای غیرحرف‌وعددی ASCII.

    فقط حروف انگلیسی (A-Z، a-z) و ارقام ASCII (0-9) نگه داشته
    می‌شوند. سایر کاراکترها (از جمله حروف فارسی و علائم) حذف می‌شوند.

    ابتدا ارقام فارسی و عربی را به ASCII تبدیل می‌کند، سپس همهٔ
    کاراکترهای به‌جز حروف انگلیسی (A-Z، a-z) و ارقام (0-9) را حذف
    می‌کند.

    Args:
        text: رشتهٔ ورودی خام.

    Returns:
        رشته‌ای که فقط شامل حروف انگلیسی و ارقام است.

    مثال:
        >>> strip_non_alphanumeric("IR82-0540-1026-8002")
        'IR82054010268002'
        >>> strip_non_alphanumeric("IR۸۲-۰۵۴۰-۱۰۲۶-۸۰۰۲")
        'IR82054010268002'
        >>> strip_non_alphanumeric("IR 12/34*56")
        'IR123456'
    """
    # گام ۱: تبدیل ارقام فارسی/عربی به ASCII
    text = normalize_digits(text)
    # گام ۲: حذف کاراکترهای غیرحرف‌وعددی
    return _NON_ALPHANUMERIC_RE.sub("", text)