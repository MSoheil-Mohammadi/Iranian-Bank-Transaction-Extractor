"""
یکسان‌سازی حروف عربی با معادل فارسی‌شان.

در متن‌های فارسی، بعضی حروف ممکن است به شکل عربی نوشته شوند که
ظاهرشان مشابه فارسی است ولی کد یونیکد متفاوتی دارند. این تفاوت
باعث می‌شود مقایسه‌های رشته‌ای و جستجوها به‌درستی کار نکنند.

حروف پرکاربرد:

    - «ي» عربی (U+064A) → «ی» فارسی (U+06CC)
    - «ى» الف مقصوره (U+0649) → «ی» فارسی
    - «ك» عربی (U+0643) → «ک» فارسی (U+06A9)
"""

from __future__ import annotations

__all__ = ["normalize_letters"]

# حروف عربی که در فارسی معادل دیگری دارند و باید یکسان‌سازی شوند.
_ARABIC_TO_PERSIAN_LETTERS = {
    "ي": "ی",  # ي عربی → ی فارسی
    "ى": "ی",  # ى الف مقصوره → ی فارسی
    "ك": "ک",  # ك عربی → ک فارسی
}

_LETTER_TRANSLATION = str.maketrans(_ARABIC_TO_PERSIAN_LETTERS)


def normalize_letters(text: str) -> str:
    """یکسان‌سازی حروف عربی با معادل فارسی‌شان.

    Args:
        text: متن ورودی.

    Returns:
        متن با حروف فارسی استاندارد.

    مثال:
        >>> normalize_letters("كتاب ي")
        'کتاب ی'
        >>> normalize_letters("مى‌روم")
        'می‌روم'
    """
    return text.translate(_LETTER_TRANSLATION)