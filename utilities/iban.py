"""
اعتبارسنجی شبا (IBAN) با الگوریتم Mod 97.

این ماژول استاندارد ISO 13616 را برای اعتبارسنجی شماره‌های شبای
ایرانی پیاده‌سازی می‌کند. شبای ایرانی ۲۶ کاراکتر دارد و همیشه با
«IR» شروع می‌شود.

ساختار شبای ایرانی:

    IR  XX  YYY  NNNNNNNNNNNNNNNNNNN
    │   │   │    │
    │   │   │    └── شماره حساب (۱۹ رقم)
    │   │   └────── کد بانک (۳ رقم)
    │   └────────── رقم کنترلی (۲ رقم)
    └────────────── کد کشور (IR)

مراحل الگوریتم Mod 97:

    ۱. چهار کاراکتر اول شبا (یعنی «IR» به‌همراه دو رقم کنترلی)
       را به انتهای رشته منتقل کن.
    ۲. حروف باقی‌مانده را با معادل عددی دو رقمی‌شان جایگزین کن.
       چون در شبای ایرانی تنها حروف موجود «I» و «R» هستند،
       این مرحله به سادگی به تبدیل زیر خلاصه می‌شود:
           I → 18
           R → 27
    ۳. رشتهٔ حاصل را به‌عنوان یک عدد صحیح بسیار بزرگ در نظر بگیر.
    ۴. باقی‌ماندهٔ تقسیم این عدد بر ۹۷ را محاسبه کن.
    ۵. اگر باقی‌مانده برابر ۱ شد، شبا معتبر است.

نکتهٔ مهم:
    Mod 97 یک «چک‌سام» است، نه یک مکانیزم امنیتی. عبور از این الگوریتم
    فقط یعنی ساختار شبا درست است. این الگوریتم تضمین نمی‌کند که حساب
    واقعاً وجود دارد یا فعال است.
"""

from __future__ import annotations

import re

from utilities.text import strip_non_alphanumeric

__all__ = [
    "clean_iban",
    "iban_check",
    "is_valid_iban",
    "IBAN_PATTERN",
    "IRAN_IBAN_LENGTH",
]

# تعداد کاراکترهای یک شبای ایرانی (شامل پیشوند IR).
IRAN_IBAN_LENGTH = 26

# معادل عددی حروف موجود در شبای ایرانی طبق استاندارد ISO 13616.
# این دیکشنری فقط حروف I و R را دارد چون تنها حروف ممکن در شبای
# ایرانی همین دو حرف هستند. برای پشتیبانی از IBAN کشورهای دیگر،
# باید این دیکشنری به کل A-Z گسترش یابد (A=10، B=11، ...، Z=35).
_IRAN_IBAN_LETTER_VALUES = {
    "I": 18,
    "R": 27,
}

# الگوی شبای ایرانی: «IR» به‌همراه ۲۴ رقم که ممکن است بین آن‌ها
# فاصله، خط تیره، اسلش یا ستاره باشد.
IBAN_PATTERN = re.compile(r"IR(?:[\s\-*/]*\d){24}", re.IGNORECASE)


def clean_iban(value: str) -> str:
    """حذف جداکننده‌ها از شبا و تبدیل آن به حروف بزرگ.

    این تابع فقط یک عملیات متنی است و **اعتبارسنجی انجام نمی‌دهد**.
    طول، پیشوند یا الگوریتم Mod 97 را بررسی نمی‌کند. اعتبارسنجی
    واقعی شبا باید با `iban_check` یا `is_valid_iban` انجام شود.

    ترکیبی از `strip_non_alphanumeric` و `str.upper`. ارقام فارسی
    و عربی نیز به‌صورت خودکار به ASCII تبدیل می‌شوند.

    Args:
        value: رشتهٔ خام شبا که ممکن است شامل فاصله یا خط تیره باشد.

    Returns:
        رشته‌ای با حروف بزرگ که فقط شامل حروف و ارقام است.

    مثال:
        >>> clean_iban("IR82 0540 1026 8002 0817 9090 02")
        'IR820540102680020817909002'
        >>> clean_iban("IR۸۲-۰۵۴۰-۱۰۲۶-۸۰۰۲-۰۸۱۷-۹۰۹۰-۰۲")
        'IR820540102680020817909002'
    """
    return strip_non_alphanumeric(value).upper()


def iban_check(iban: str) -> bool:
    """اعتبارسنجی شبای ایرانی با الگوریتم Mod 97 (ISO 13616).

    Args:
        iban: رشتهٔ شبا پس از پاک‌سازی (بدون جداکننده) که با «IR» شروع می‌شود.

    Returns:
        اگر شبا از فیلتر Mod 97 عبور کند True، در غیر این صورت False.

    مثال:
        >>> iban_check("IR820540102680020817909002")
        True
        >>> iban_check("IR820540102680020817909003")
        False
    """
    # گام ۰: بررسی ساختار پایه‌ای شبای ایرانی.
    # شبای ایرانی دقیقاً ۲۶ کاراکتر است: IR + ۲۴ رقم.
    if len(iban) != IRAN_IBAN_LENGTH:
        return False
    if not iban.startswith("IR"):
        return False
    if not iban[2:].isdigit():
        return False

    # گام ۱: چهار کاراکتر اول (IR + دو رقم کنترلی) را به انتها منتقل می‌کنیم.
    rearranged = iban[4:] + iban[:4]

    # گام ۲: حروف را به معادل عددی‌شان تبدیل می‌کنیم.
    # چون فقط شبای ایرانی پشتیبانی می‌شود، تنها حروف ممکن I و R هستند.
    numeric_str = ""
    for char in rearranged:
        if char.isdigit():
            numeric_str += char
        elif char in _IRAN_IBAN_LETTER_VALUES:
            numeric_str += str(_IRAN_IBAN_LETTER_VALUES[char])
        else:
            # کاراکتر غیرمنتظره در شبا
            return False

    # گام ۳ و ۴: باقی‌ماندهٔ تقسیم عدد بزرگ بر ۹۷ را محاسبه می‌کنیم.
    return int(numeric_str) % 97 == 1


def is_valid_iban(iban: str) -> bool:
    """بررسی معتبر بودن یک شبای خام به‌صورت یک‌جا.

    این تابع پاک‌سازی و اعتبارسنجی Mod 97 را در یک فراخوانی ترکیب می‌کند.

    Args:
        iban: رشتهٔ خام شبا که ممکن است شامل فاصله یا خط تیره باشد.

    Returns:
        اگر شبای پاک‌سازی‌شده معتبر باشد True، در غیر این صورت False.
    """
    return iban_check(clean_iban(iban))