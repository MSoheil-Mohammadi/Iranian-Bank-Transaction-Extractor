"""
پیاده‌سازی الگوریتم Luhn (یا Mod 10).

الگوریتم Luhn یک فرمول چک‌سام ساده است که برای اعتبارسنجی انواع
شماره‌های شناسایی استفاده می‌شود؛ از جمله:

    - شماره کارت‌های بانکی (ویزا، مسترکارت و ...)
    - شماره IMEI گوشی‌های موبایل
    - شماره‌های بیمه و برخی شناسه‌های ملی

این الگوریتم توسط «هانس پیتر لوهن» در دههٔ ۱۹۵۰ میلادی ابداع شد و
در استاندارد ISO/IEC 7812-1 تعریف شده است.

نکتهٔ مهم:
    Luhn یک «چک‌سام» است، نه یک مکانیزم امنیتی. عبور از این الگوریتم
    فقط یعنی شماره از نظر ساختاری درست ساخته شده است. این الگوریتم
    تضمین نمی‌کند که کارت واقعاً وجود دارد، فعال است یا متعلق به کیست.
"""

from __future__ import annotations

import re

from utilities.text import strip_non_digits

__all__ = ["luhn_check", "clean_card", "is_valid_card"]

# الگوی شماره کارت: ۱۶ رقم که ممکن است با فاصله یا خط تیره از هم جدا شده باشند.
# رقم اول بین ۱ تا ۹ است (بدون صفر ابتدایی) و بقیه ارقام آزادند.
CARD_PATTERN = re.compile(
    r"\b[1-9]\d{3}[\s-]?\d{4}[\s-]?\d{4}[\s-]?\d{4}\b"
)


def clean_card(value: str) -> str:
    """حذف کاراکترهای غیرعددی از یک شماره کارت.

    این تابع فقط یک عملیات متنی است و **اعتبارسنجی انجام نمی‌دهد**.
    طول، ساختار یا الگوریتم Luhn را بررسی نمی‌کند. اعتبارسنجی واقعی
    کارت باید با `luhn_check` یا `is_valid_card` انجام شود.

    این تابع یک alias برای `utilities.text.strip_non_digits` است و
    صرفاً برای خوانایی بیشتر در context کارت بانکی وجود دارد.

    Args:
        value: رشتهٔ خام شماره کارت که ممکن است شامل فاصله یا خط تیره باشد.

    Returns:
        رشته‌ای که فقط شامل ارقام است.
    """
    return strip_non_digits(value)


def luhn_check(card: str) -> bool:
    """اعتبارسنجی یک رشتهٔ عددی با الگوریتم Luhn.

    مراحل الگوریتم به این شکل است:

        ۱. از سمت راست شروع کن و هر رقم دوم را دو برابر کن.
        ۲. اگر حاصل دو برابر شدن بزرگ‌تر از ۹ شد، ۹ واحد از آن کم کن.
        ۳. همهٔ ارقام را با هم جمع بزن.
        ۴. اگر مجموع بر ۱۰ بخش‌پذیر بود، شماره معتبر است.

    Args:
        card: رشته‌ای از ارقام (بدون جداکننده).

    Returns:
        اگر شماره از فیلتر Luhn عبور کند True، در غیر این صورت False.

    مثال:
        >>> luhn_check("4111111111111111")
        True
        >>> luhn_check("4111111111111112")
        False
    """
    # محافظ: رشته خالی یا شامل کاراکتر غیرعددی نباید به الگوریتم برسد.
    if not card or not card.isdigit():
        return False

    # رشته را برعکس می‌کنیم تا از سمت راست پردازش کنیم.
    digits = [int(d) for d in card[::-1]]
    total = 0

    for index, digit in enumerate(digits):
        # هر رقم دوم (از راست) دو برابر می‌شود.
        if index % 2 == 1:
            digit *= 2
            if digit > 9:
                digit -= 9
        total += digit

    # اگر مجموع بر ۱۰ بخش‌پذیر باشد، شماره معتبر است.
    return total % 10 == 0


def is_valid_card(card: str) -> bool:
    """بررسی معتبر بودن یک شماره کارت خام به‌صورت یک‌جا.

    این تابع پاک‌سازی و اعتبارسنجی Luhn را در یک فراخوانی ترکیب می‌کند.

    Args:
        card: رشتهٔ خام شماره کارت که ممکن است شامل فاصله یا خط تیره باشد.

    Returns:
        اگر شماره پس از پاک‌سازی دقیقاً ۱۶ رقم باشد و از Luhn عبور کند، True.
    """
    cleaned = clean_card(card)
    return len(cleaned) == 16 and luhn_check(cleaned)