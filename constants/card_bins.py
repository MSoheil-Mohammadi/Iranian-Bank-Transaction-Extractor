def get_bank_by_bin(card: str) -> str:
    """نام بانک را بر اساس BIN کارت برمی‌گرداند.

    Args:
        card: شماره کارت (حداقل ۶ رقم).

    Returns:
        نام بانک، یا «نامشخص» در صورت عدم تطابق.

    مثال:
        >>> get_bank_by_bin("6037991234567890")
        'بانک ملی ایران'
        >>> get_bank_by_bin("123")
        'نامشخص'
    """
    if len(card) < 6:
        return "نامشخص"
    return CARD_BANKS.get(card[:6], "نامشخص")